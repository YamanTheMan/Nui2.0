export function getFactsForQuery(query: string): string {
  const matched: string[] = [];
  const seen = new Set<string>();

  const add = (fact: string) => {
    if (!seen.has(fact)) {
      seen.add(fact);
      matched.push(fact);
    }
  };

  for (const [pattern, fact] of TOPIC_PATTERNS) {
    if (pattern.test(query)) add(fact);
  }

  const lower = query.toLowerCase();
  if (["assignment", "assignments", "deliverable", "rubric"].some((w) => lower.includes(w))) {
    [ASSIGNMENT_1, ASSIGNMENT_2, FINAL_PROJECT, SELF_REFLECTIVE].forEach(add);
  }
  if (["grade", "grading", "score", "percent", "worth"].some((w) => lower.includes(w))) {
    [GRADE_DISTRIBUTION, WOW_FACTOR].forEach(add);
  }

  return matched.join("\n\n---\n\n");
}

